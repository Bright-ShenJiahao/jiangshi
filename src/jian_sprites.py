# 第四位主角：青城剑客（样稿，尚未接入游戏）。需先 exec sprites.py（Spr / PAL）；热血物语式大头，身高与道长一致
PAL.update({'ql': (70, 170, 190), 'qd': (30, 96, 120), 'qr': (190, 232, 240)})


def jianke(drawn=False, step=0):
    """青城剑客：黑发高髻插玉簪、青白发带飘在脑后；青色短道袍、白交领、深蓝腰带、白护腕绑腿；背后斜背长剑。drawn=握剑出鞘"""
    s = Spr(26, 37)
    R, P = s.rect, s.px
    # 背后的巨剑：斜背，45 度一条直线——剑柄在右肩上方，剑尖越过左髋露在身后；宽剑身、粗剑柄、大护手
    for t in range(0, 22):
        x, y = 21 - t, 11 + t                      # 剑身中线，每下一行向左一格
        R(x - 2, y, x + 2, y, 'G'); R(x - 1, y, x + 1, y, 'W'); P(x + 1, y, 'g'); P(x - 2, y, 'E')
    for t in (4, 10, 16): R(21 - t - 2, 11 + t, 21 - t + 2, 11 + t, 'E')                  # 剑身血槽分段
    P(0, 32, 'G'); P(1, 32, 'W'); P(0, 33, 'G')                                           # 剑尖
    for k in range(0, 5):                                                                  # 缠布剑柄（沿同一条斜线向右上）
        x, y = 22 + k, 10 - k
        P(x - 1, y, 'B'); P(x, y, 'B' if k % 2 else 'O'); P(x + 1, y, 'B')
    R(26 - 1, 5, 26, 6, 'r'); P(25, 7, 'r')                                               # 红穗
    for k in range(-3, 4):                                                                 # 护手：与剑身垂直的横档（沿 45 度）
        x, y = 21 + k, 10 + k
        P(x, y, 'o'); P(x + 1, y, 'O')
    # 发带（青白相间）从发髻飘向右后方
    for x, y, c in [(15, 1, 'ql'), (16, 1, 'qr'), (17, 2, 'ql'), (18, 2, 'qr'), (19, 3, 'ql'), (20, 4, 'qr'), (21, 6, 'ql'), (20, 8, 'qr'), (21, 10, 'ql')]:
        P(x, y, c); P(x, y + 1, c)
    # 头发：高髻 + 玉簪 + 鬓发（大头：脸 12 宽）
    R(11, 0, 14, 2, 'k'); P(12, 0, 'H'); R(8, 3, 17, 7, 'k'); R(6, 5, 7, 14, 'k'); R(18, 5, 19, 14, 'k'); R(7, 4, 8, 4, 'k'); R(17, 4, 18, 4, 'k')
    R(11, 2, 14, 2, 'qd'); P(12, 2, 'j'); P(13, 2, 'j')                                  # 青色束发带 + 玉簪
    # 脸：尖下巴、剑眉、目光锐利
    R(7, 7, 18, 16, 's'); R(7, 7, 7, 15, 'S'); s.clear((7, 16), (18, 16)); P(7, 16, 'k'); P(18, 16, 'k')
    R(8, 6, 17, 6, 'k'); R(8, 7, 9, 8, 'k'); R(16, 7, 17, 8, 'k'); P(12, 7, 'k'); P(13, 7, 'k')   # 刘海，中间留一缝
    R(8, 10, 11, 10, 'k'); R(14, 10, 17, 10, 'k'); P(8, 9, 'k'); P(17, 9, 'k')               # 剑眉
    R(9, 11, 10, 13, 'k'); P(10, 11, 'w'); R(15, 11, 16, 13, 'k'); P(16, 11, 'w')            # 眼
    R(12, 14, 13, 14, 'S')
    # 青色短道袍 + 白交领
    R(8, 17, 17, 28, 'ql'); R(8, 17, 9, 28, 'qd'); R(16, 17, 17, 28, 'qd')
    R(10, 17, 15, 17, 'w'); P(11, 18, 'w'); P(12, 19, 'w'); P(13, 20, 'w'); P(12, 18, 'w'); P(14, 18, 'w'); P(15, 19, 'w'); R(12, 17, 13, 18, 'S')
    R(8, 23, 17, 25, 'N'); R(8, 23, 17, 23, 'n'); P(14, 24, 'j'); P(14, 25, 'j'); P(15, 26, 'qr'); P(15, 27, 'qr')   # 深蓝腰带、玉佩
    for t in range(0, 10): P(16 - t, 18 + t, 'B'); P(15 - t, 18 + t, 'B')              # 斜挎的剑带：右肩到左髋
    P(12, 22, 'o'); P(13, 21, 'o')
    # 左臂（观众左）自然垂下，白护腕 + 手
    R(5, 18, 7, 24, 'ql'); R(5, 18, 5, 24, 'qd'); R(5, 25, 7, 26, 'w'); R(5, 27, 7, 28, 's')
    R(18, 18, 20, 22, 'ql'); R(18, 18, 18, 22, 'qd'); R(18, 23, 20, 25, 'w'); R(17, 25, 19, 26, 's')
    # 裤子：深蓝、白绑腿；黑布鞋。step=0 站立，1/2 迈左/右腿
    lh = [0, 2, 0][step]; rh = [0, 0, 2][step]
    R(9, 29, 12, 33 - lh, 'n'); R(14, 29, 17, 33 - rh, 'n'); R(9, 31 - lh, 12, 32 - lh, 'w'); R(14, 31 - rh, 17, 32 - rh, 'w')
    R(8, 34 - lh, 12, 35 - lh, 'k'); R(14, 34 - rh, 18, 35 - rh, 'k'); P(9, 34 - lh, 'H'); P(15, 34 - rh, 'H')
    s.outline()
    return s
