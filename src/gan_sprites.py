    # 黑衣，前襟露红衬
    R(7, 18, 17, 30, 'h'); R(6, 25, 18, 30, 'h')
    R(7, 18, 8, 30, 'k'); R(6, 25, 6, 30, 'k')
    if red:
        R(12, 18, 13, 30, 'r'); R(12, 18, 12, 30, 'X')
        R(6, 30, 18, 30, 'X')
    R(7, 23, 17, 23, 'sT')                                      # 草绳腰带
    # 双臂平伸（袖口红边），惨白的手
