    R(2, 5, 22, 5, 'sT'); P(12, 0, 'sL')
    for x in range(4, 21, 3): P(x, 4, 'sT')
    for x in (10, 12, 14): P(x, 2, 'sT')
    R(10, 1, 11, 1, 'sL')
    # 黑布：从笠沿垂到胸口，盖住整张脸
    R(7, 6, 17, 17, 'cb'); R(7, 6, 8, 17, 'k'); R(16, 6, 17, 16, 'cB')
    for x in (9, 12, 15): R(x, 7, x, 16, 'cB')
