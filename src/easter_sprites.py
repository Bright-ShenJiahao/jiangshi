def captain(hat=True):
    """民国警察队长：大檐帽金徽、八字胡、深藏青制服金扣、斜挎皮带、手枪"""
    s = Spr(26, 36)
    if hat:
        s.rect(7, 2, 17, 5, 'N'); s.rect(6, 4, 18, 6, 'n'); s.rect(7, 2, 17, 2, 'n')
        s.rect(11, 3, 13, 4, 'o'); s.px(12, 3, 'p')
        s.rect(13, 7, 20, 7, 'k')                         # 帽檐朝前
    else:
        s.rect(8, 5, 16, 7, 'h'); s.rect(9, 4, 15, 4, 'h')  # 头发（帽子掉了）
    s.rect(8, 8, 17, 17, 's'); s.rect(8, 8, 9, 16, 'S'); s.clear((8, 17), (17, 17))
    s.px(13, 11, 'k'); s.px(16, 11, 'k'); s.rect(12, 10, 13, 10, 'h'); s.rect(15, 10, 16, 10, 'h')
    s.px(18, 12, 's')
    s.rect(13, 14, 17, 14, 'k'); s.px(12, 15, 'k'); s.px(18, 15, 'k')   # 八字胡
    s.rect(14, 16, 16, 16, 'S')
    # 制服
    s.rect(7, 18, 18, 28, 'n'); s.rect(7, 18, 9, 28, 'N'); s.rect(10, 18, 15, 19, 'N')
    for y in (20, 23, 26): s.px(13, y, 'o')
    s.rect(7, 25, 18, 25, 'B'); s.px(13, 25, 'o')                      # 腰带
    for i in range(7): s.px(9 + i, 18 + i, 'b')                         # 斜挎皮带
    s.rect(15, 21, 17, 22, 'N')                                         # 口袋
    # 举枪的手
    s.rect(16, 19, 21, 21, 'n'); s.rect(21, 18, 22, 21, 's')
    s.rect(22, 17, 25, 18, 'h'); s.rect(22, 19, 23, 20, 'h')
    s.rect(4, 19, 7, 25, 'N'); s.rect(4, 25, 6, 26, 's')
    # 裤子马靴
    s.rect(8, 29, 11, 31, 'n'); s.rect(14, 29, 17, 31, 'n')
    s.rect(8, 32, 11, 34, 'k'); s.rect(14, 32, 18, 34, 'k'); s.px(9, 32, 'H'); s.px(15, 32, 'H')
    s.outline()
    return s


