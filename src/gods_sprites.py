def _disc(s, cx, cy, r, c, ring=False):
    for y in range(cy - r, cy + r + 1):
        for x in range(cx - r, cx + r + 1):
            d = (x - cx) ** 2 + (y - cy) ** 2
            if (d <= r * r and not ring) or (ring and r * r - 2 * r <= d <= r * r + r):
                s.px(x, y, c)

