# 第三位主角：天主圣徒 Father 柴
# 需先 exec sprites.py 的定义（Spr / PAL）；身高与道长一致
# 画布统一 34x39（左右各留 4 格给翅膀，顶上留 2 格给光晕），所有形态叠在同一位置，切换时不跳动

PAL.update({
    'ae': (255, 236, 150),   # 天使金发/光晕亮部
    'aw': (248, 248, 255),   # 天使白袍
    'ag': (200, 206, 228),   # 白袍阴影
    'am': (66, 18, 30),      # 蝙蝠翼膜（暗）
    'aM': (120, 28, 44),     # 蝙蝠翼膜（亮）
})


def priest(gun=False, form=''):
    """form: '' 普通；'v' 吸血鬼神官（红眼獠牙、蝙蝠翼、血色圣带）；'l' 光明神官（脑后金色光晕）"""
    s = Spr(34, 39, oy=2)
    O = 4
    R = lambda x0, y0, x1, y1, c: s.rect(x0 + O, y0, x1 + O, y1, c)
    P = lambda x, y, c: s.px(x + O, y, c)
    vamp, light = form == 'v', form == 'l'
    skin, skinS = ('W', 'G') if vamp else ('s', 'S')
    stole, stoleS, mark = ('r', 'X', 'k') if vamp else ('w', 'W', 'o')
    # 吸血鬼：背后一对蝙蝠翼（先画，身体盖在上面）
    if vamp:
        for side in (-1, 1):
            cx = 13 + side * 6
            for i in range(11):                      # 翼膜：肩膀往外，上缘斜升，下缘呈扇贝状
                x = cx + side * i
                top = 15 - (i * 8) // 10
                bot = 25 - i // 2 - (3 if i % 4 == 3 else 0)
                for y in range(top, bot):
                    P(x, y, 'aM' if y - top < 2 else 'am')
                P(x, top, 'k')
            for i in (3, 7):                         # 翼骨
                x = cx + side * i
                for y in range(15 - (i * 8) // 10, 22 - i // 2):
                    P(x, y, 'k')
    # 光明：脑后圆盘光轮（像圣像画里的光环：浅金色圆盘，外圈一道深金色描边），画在头发后面
    if light:
        cx, cy, r = 13, 6.5, 10.2
        for y in range(-2, 17):
            for x in range(1, 26):
                d = ((x - cx) ** 2 + (y - cy) ** 2) ** 0.5
                if d <= r:
                    P(x, y, 'O' if d > r - 1.1 else 'ae' if d < r - 2.6 else 'p')
    # 黑色中长发
    R(10, 1, 16, 1, 'k'); R(9, 2, 17, 3, 'k'); R(8, 3, 18, 14, 'k')                     # 长发：脑后一大片，垂过肩膀
    R(7, 8, 8, 17, 'k'); R(18, 8, 19, 16, 'k')
    # 脸
    R(10, 6, 16, 12, skin); R(10, 6, 10, 11, skinS)
    s.clear((10 + O, 12), (16 + O, 12)); P(10, 12, 'k'); P(16, 12, 'k')
    R(10, 5, 12, 5, 'k'); R(14, 5, 16, 5, 'k'); R(10, 6, 10, 7, 'k'); R(16, 6, 16, 7, 'k')   # 中分刘海，两侧发丝垂在脸旁
    R(11, 7, 12, 7, 'k'); R(14, 7, 15, 7, 'k')                   # 细眉
    for cx in (11, 15):                                          # 圆眼镜（吸血鬼形态摘掉眼镜，只剩红眼）
        if not vamp: P(cx, 8, 'G'); P(cx, 10, 'G'); P(cx - 1, 9, 'G'); P(cx + 1, 9, 'G')
        P(cx, 9, 'r' if vamp else 'k')
    if not vamp: P(13, 9, 'G')
    R(12, 11, 14, 11, 'X' if vamp else skinS)                     # 嘴
    if vamp:
        P(12, 12, 'w'); P(14, 12, 'w')                           # 獠牙
    # 罗马领
    R(12, 13, 14, 13, 'w')
    # 短披肩
    R(7, 14, 19, 18, 'h'); R(7, 14, 8, 18, 'H'); R(8, 18, 18, 18, 'H')
    if vamp:
        R(7, 13, 8, 15, 'X'); R(18, 13, 19, 15, 'X')             # 立起的血色高领
    # 长发飘飘：两束长发从头两侧披过肩膀垂到腰际，发梢被风吹向身后（左飘右）
    R(8, 12, 10, 21, 'k'); R(7, 18, 9, 25, 'k'); R(6, 24, 8, 28, 'k'); P(5, 27, 'k'); P(5, 28, 'k')
    R(17, 12, 18, 20, 'k'); R(17, 18, 19, 24, 'k'); R(18, 23, 20, 27, 'k'); P(20, 28, 'k')
    for y in (14, 17, 20, 23): P(9 if y < 22 else 8, y, 'H'); P(8 if y < 22 else 7, y + 1, 'H')
    for y in (15, 18, 21): P(18, y, 'H')
    P(4, 29, 'k'); P(3, 30, 'k'); P(21, 29, 'k'); P(22, 30, 'k')                 # 发梢飘起
    P(10, 2, 'H'); P(11, 3, 'H'); P(15, 2, 'H'); P(9, 6, 'H'); P(9, 9, 'H'); P(17, 6, 'H'); P(17, 10, 'H'); P(8, 12, 'H')   # 发丝反光
    # 长袍
    R(9, 19, 17, 32, 'h'); R(8, 27, 18, 32, 'h'); R(9, 19, 9, 32, 'H'); R(8, 27, 8, 32, 'H')
    R(13, 21, 13, 31, 'H')
    # 圣带（光明/普通：白底金十字；吸血鬼：血红底黑十字）
    for x in (11, 15):
        R(x, 14, x, 31, stole); R(x + 1, 14, x + 1, 31, stoleS)
    for y in (21, 28):
        for x in (11, 15):
            P(x, y - 1, mark); P(x, y, mark); P(x + 1, y, mark); P(x, y + 1, mark)
    for x in (11, 12, 15, 16):
        P(x, 32, 'X' if vamp else 'p')
    # 胸前十字
    c1, c2 = ('X', 'm') if vamp else ('W', 'G')
    P(13, 16, c1); P(13, 17, c1); P(12, 17, c2); P(14, 17, c2); P(13, 18, c1)
    # 左臂自然垂下，白手套
    R(6, 17, 7, 24, 'h'); R(6, 17, 6, 24, 'H'); R(6, 25, 7, 26, 'w')
    if gun:   # 银色雕花手枪，枪口朝下贴着腿
        g1, g2, eng = ('r', 'X', 'k') if vamp else ('W', 'G', 'o')   # 吸血鬼形态：血红色手枪
        R(5, 25, 5, 27, g2); R(4, 26, 4, 27, g2)                 # 握把
        R(6, 27, 7, 33, g1); R(6, 27, 6, 33, g2)                 # 枪管
        P(7, 29, eng); P(7, 31, eng); P(5, 26, eng)               # 雕花
        P(6, 34, 'k'); P(7, 34, 'k')
    # 右臂抬起 → 托着圣经
    R(19, 17, 20, 21, 'h'); R(19, 22, 21, 23, 'w')
    cov, covS = ('V', 'k') if vamp else ('m', 'M')
    R(20, 10, 24, 21, cov); R(20, 10, 20, 21, covS); R(21, 10, 24, 10, 'p'); R(24, 11, 24, 21, 'p')
    if vamp:
        R(22, 13, 22, 18, 'r'); R(21, 16, 23, 16, 'r')            # 禁书：倒十字
    else:
        R(22, 12, 22, 17, 'o'); R(21, 14, 23, 14, 'o')
    # 鞋
    R(10, 33, 12, 34, 'k'); R(14, 33, 16, 34, 'k'); P(11, 33, 'h'); P(15, 33, 'h')
    s.outline()
    return s


def angel():
    """天使之怒：小号天使（约比神父高一个头），白袍金发、白翼、光环，双手高举巨剑"""
    s = Spr(44, 52, oy=0)
    R, P = s.rect, s.px
    # 翅膀
    for side in (-1, 1):
        for i in range(13):
            x0 = 22 + side * (5 + i)
            top = 16 - i // 2 - (2 if i > 8 else 0)
            bot = 30 - i // 3
            for y in range(top, bot):
                P(x0, y, 'aw' if (y - top) < (bot - top) * 0.6 else 'ag')
            P(x0, top, 'ag')
    # 光环
    for y in range(0, 22):
        for x in range(10, 35):
            d = ((x - 22) ** 2 + (y - 11) ** 2) ** 0.5
            if d <= 10.5:
                P(x, y, 'O' if d > 9.4 else 'ae' if d < 8 else 'p')
    # 金发与脸
    R(18, 7, 26, 16, 'b'); R(17, 9, 18, 18, 'b'); R(26, 9, 27, 18, 'B'); R(19, 7, 25, 8, 'L')
    R(19, 10, 25, 16, 's'); R(19, 10, 19, 15, 'S')
    R(20, 12, 21, 12, 'k'); R(23, 12, 24, 12, 'k'); R(21, 15, 23, 15, 'S')
    # 白袍
    for y in range(17, 44):
        hw = 4 + (y - 17) // 3
        R(22 - hw, y, 22 + hw, y, 'aw')
        P(22 - hw, y, 'ag'); P(22 - hw + 1, y, 'ag')
    R(18, 24, 26, 24, 'o')                                       # 金腰带
    R(14, 44, 30, 44, 'ag')
    # 双手在胸前合握（巨剑由游戏代码另画，好做举剑、劈下的动画）
    R(17, 18, 18, 23, 'aw'); R(26, 18, 27, 23, 'aw'); R(19, 21, 25, 22, 's')
    s.outline()
    return s


def cherub():
    """圣经救赎出的小天使：金发、白翼、光环"""
    s = Spr(16, 16)
    R, P = s.rect, s.px
    R(1, 5, 4, 9, 'aw'); R(11, 5, 14, 9, 'aw'); P(1, 9, 'ag'); P(14, 9, 'ag')
    for y in range(0, 9):
        for x in range(3, 13):
            d = ((x - 7.5) ** 2 + (y - 4) ** 2) ** 0.5
            if d <= 4.6:
                P(x, y, 'O' if d > 3.7 else 'p')
    R(5, 2, 10, 7, 'L'); R(6, 4, 9, 7, 's'); P(6, 5, 'k'); P(9, 5, 'k')
    R(5, 8, 10, 13, 'aw'); R(5, 8, 5, 13, 'ag')
    s.outline()
    return s
